#!/usr/bin/env bash
# Builds sappa_core for iOS and generates its Swift bindings.
#
# Outputs (in dist/ios):
#   iphoneos/libsappa_core.a          device (arm64)
#   iphonesimulator/libsappa_core.a   simulator (arm64 + x86_64)
#   include/sappa_coreFFI/            C header + module.modulemap
#   bindings/sappa_core.swift         generated Swift API
#   SappaCore.xcframework             same libraries, packaged (binary target of Package.swift)
#
# The Swift bindings are also written to swift/Sources/SappaCore/SappaCore.swift, the Swift
# target of the `SappaCore` package that the iOS app depends on. Runs the same locally and in CI.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

if ! command -v cargo >/dev/null 2>&1; then
  for p in /opt/homebrew/opt/rustup/bin "$HOME/.cargo/bin"; do
    [ -x "$p/cargo" ] && export PATH="$p:$PATH" && break
  done
fi

export IPHONEOS_DEPLOYMENT_TARGET="${IPHONEOS_DEPLOYMENT_TARGET:-26.0}"
PROFILE="${PROFILE:-release}"
DEVICE=aarch64-apple-ios
SIMS=(aarch64-apple-ios-sim x86_64-apple-ios)
OUT="$ROOT/dist/ios"

rustup target add "$DEVICE" "${SIMS[@]}" >/dev/null

flag=(--release)
[ "$PROFILE" = "debug" ] && flag=()

echo "==> cargo build ($PROFILE) for $DEVICE ${SIMS[*]}"
for t in "$DEVICE" "${SIMS[@]}"; do
  cargo build "${flag[@]}" --lib --target "$t"
done

rm -rf "$OUT"
mkdir -p "$OUT/iphoneos" "$OUT/iphonesimulator" "$OUT/include/sappa_coreFFI" "$OUT/bindings"

cp "target/$DEVICE/$PROFILE/libsappa_core.a" "$OUT/iphoneos/"
lipo -create \
  "target/${SIMS[0]}/$PROFILE/libsappa_core.a" \
  "target/${SIMS[1]}/$PROFILE/libsappa_core.a" \
  -output "$OUT/iphonesimulator/libsappa_core.a"

echo "==> generating Swift bindings"
cargo run --quiet --features bindgen --bin uniffi-bindgen -- generate \
  --library "target/$DEVICE/$PROFILE/libsappa_core.a" \
  --language swift --out-dir "$OUT/bindings"

mv "$OUT/bindings/sappa_coreFFI.h" "$OUT/include/sappa_coreFFI/"
mv "$OUT/bindings/sappa_coreFFI.modulemap" "$OUT/include/sappa_coreFFI/module.modulemap"

echo "==> packaging SappaCore.xcframework"
xcodebuild -create-xcframework \
  -library "$OUT/iphoneos/libsappa_core.a" -headers "$OUT/include/sappa_coreFFI" \
  -library "$OUT/iphonesimulator/libsappa_core.a" -headers "$OUT/include/sappa_coreFFI" \
  -output "$OUT/SappaCore.xcframework" >/dev/null

dest="$ROOT/swift/Sources/SappaCore"
mkdir -p "$dest"
{
  echo "// GENERATED by scripts/build-ios.sh from sappa_core $(grep -m1 '^version' Cargo.toml | cut -d'"' -f2). Do not edit."
  cat "$OUT/bindings/sappa_core.swift"
} > "$dest/SappaCore.swift"
echo "==> wrote Swift package sources to $dest/SappaCore.swift"

echo "done: $OUT"
